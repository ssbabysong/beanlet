import assert from 'node:assert/strict';
import {buildWidgetSnapshot,parseWidgetLink,thumbKey} from '../lib/widget-snapshot.ts';
import {beanStock} from '../lib/bean-stock.ts';
import {bagColorIndex,beanPalette,bagColors} from '../lib/bean-appearance.ts';
const beans=[{id:'a',name:'A',weight:200,status:'正在喝',icon:'peach'},{id:'b',name:'B',status:'未开封',icon:'cookie',photo:'data:image/png;base64,AA'},{id:'c',name:'C',weight:250,status:'已喝完'},{id:'d',name:'D',status:'未开封'},{id:'e',name:'E',status:'未开封'},{id:'f',name:'F',status:'未开封'}];
const brews=[{beanId:'b',date:'2026-10-08',kind:'milk',dose:16},{beanId:'a',date:'2026-10-08',dose:15},{beanId:'a',date:'2026-10-07',dose:15},{beanId:'a',date:'2025-01-01',dose:15}];
const input={beans,brews,language:'zh',today:'2026-10-08',preference:{},name:b=>b.name,roaster:()=>'',palette:b=>beanPalette(b,false),art:b=>b.photo||'',stock:b=>beanStock(b,brews)};
const {snapshot,thumbs}=buildWidgetSnapshot(input);
assert.equal(snapshot.shelfCount,5);
assert.deepEqual(snapshot.shelf.map(b=>b.id),['a','b','d','e','f']);
assert.equal(snapshot.shelf[0].remaining,155);
assert.equal(snapshot.shelf[1].remaining,null);
assert.equal(snapshot.shelf[1].icon,'brownie');
assert.equal(snapshot.shelf[1].thumb,thumbKey('data:image/png;base64,AA'));
assert.deepEqual(Object.values(thumbs),['data:image/png;base64,AA']);
// A plain photo stays a label on the paper pouch; a cut-out bag photo is flagged so the widget draws the real bag.
assert.equal(snapshot.shelf[1].cutout,undefined);
assert.equal(buildWidgetSnapshot({...input,beans:beans.map(b=>b.id==='b'?{...b,photoCutout:true}:b)}).snapshot.shelf[1].cutout,true);
assert.equal(buildWidgetSnapshot({...input,beans:beans.map(b=>b.id==='a'?{...b,photoCutout:true}:b)}).snapshot.shelf[0].cutout,undefined);
assert.equal(snapshot.brewBean.id,'b');
assert.equal(snapshot.brewKind,'milk');
assert.equal(snapshot.days['2026-10-08'].c,2);
assert.equal(snapshot.days['2026-10-08'].k.length,2);
assert.equal(snapshot.days['2025-01-01'],undefined);
assert.equal(buildWidgetSnapshot({...input,preference:{beanId:'d',kind:'pourOver'}}).snapshot.brewBean.id,'d');
assert.equal(buildWidgetSnapshot({...input,preference:{beanId:'c'}}).snapshot.brewBean.id,'b');
assert.equal(buildWidgetSnapshot({...input,beans:[],brews:[]}).snapshot.brewBean,null);
assert.notEqual(thumbKey('x'),thumbKey('y'));
assert.deepEqual(parseWidgetLink('beanlet://brew'),{kind:'brew'});
assert.deepEqual(parseWidgetLink('beanlet://bean/a%2Fb'),{kind:'bean',id:'a/b'});
assert.equal(parseWidgetLink('beanlet://bean'),null);
assert.equal(parseWidgetLink('https://example.com'),null);
assert.equal(parseWidgetLink('beanlet://unknown'),null);
// Chosen bag colors win; older bags keep a stable default.
assert.equal(bagColorIndex({id:'x',icon:'peach',bagColor:2}),2);
assert.equal(bagColorIndex({id:'x',icon:'peach'}),7);
assert.equal(bagColorIndex({id:'x',icon:'peach',bagColor:99}),7);
assert.equal(bagColorIndex({id:'x',icon:'peach',photo:'p'}),bagColorIndex({id:'x',icon:'bag',photo:'p'}));
assert.ok(bagColorIndex({id:'x',photo:'p'})<bagColors.length);
console.log('Widget snapshot: shelf, brew bean, history, thumbnails, links and bag colors passed');
